class FontGlyphInjector(MioRomResult):
    """
    Console Font Glyph Injector and Proportional Width Table Generator.
    Injects Latin characters, numbers, and punctuation into 1bpp/2bpp/4bpp font tables in ROM/VRAM.
    """

    @classmethod
    def get_tile(cls, char: str, fg_color: int = 1, bg_color: int = 0) -> Tile:
        """Constructs an 8x8 Tile for the specified character."""
        rows = LATIN_8X8_BITMAPS.get(char)
        if rows is None:
            # Fallback to '?'
            rows = LATIN_8X8_BITMAPS.get("?", (0,) * 8)

        pixels = [bg_color] * 64
        for y in range(8):
            row = rows[y]
            for x in range(8):
                if (row >> (7 - x)) & 1:
                    pixels[y * 8 + x] = fg_color

        return Tile(pixels)

    @classmethod
    def get_glyph(cls, char: str, advance: Optional[int] = None) -> Glyph:
        """Constructs a high-level Glyph object with pixel matrix and advance."""
        from miorom.text.font_builder import Glyph

        tile = cls.get_tile(char)
        width = cls.calculate_glyph_width(char, padding=1)
        adv = advance if advance is not None else (width + 1)
        # 0-255 bitmap representation
        bitmap = [255 if p != 0 else 0 for p in tile.pixels]
        return Glyph(char=char, width=8, height=8, advance=adv, bitmap=bitmap)

    @classmethod
    def calculate_glyph_width(
        cls,
        char_or_tile: Union[str, Tile],
        padding: int = 1,
        space_width: int = 3,
        min_width: int = 1,
        max_width: int = 8,
    ) -> int:
        """
        Calculates the bounding-box width in pixels for a character.
        Used for proportional variable-width fonts (VWF).
        """
        if isinstance(char_or_tile, str):
            if char_or_tile == " ":
                return space_width
            tile = cls.get_tile(char_or_tile)
        else:
            tile = char_or_tile

        # Find leftmost and rightmost non-zero columns
        min_x = 8
        max_x = -1
        for y in range(8):
            for x in range(8):
                if tile.get_pixel(x, y) != 0:
                    if x < min_x:
                        min_x = x
                    if x > max_x:
                        max_x = x

        if max_x == -1:
            return space_width

        raw_width = (max_x - min_x + 1) + padding
        return max(min_width, min(max_width, raw_width))

    @classmethod
    def encode_glyph_tile(
        cls,
        char_or_tile: Union[str, Tile],
        bpp: int = 1,
        format: Optional[str] = None,
        fg_color: int = 1,
        bg_color: int = 0,
    ) -> bytes:
        """Encodes an 8x8 character tile into binary bytes for target console architecture."""
        if isinstance(char_or_tile, str):
            tile = cls.get_tile(char_or_tile, fg_color=fg_color, bg_color=bg_color)
        else:
            tile = char_or_tile

        return encode_tile(tile, bpp=bpp, format=format)

    @classmethod
    def get_tile_byte_size(cls, bpp: int = 1, format: Optional[str] = None) -> int:
        """Returns byte size of a single 8x8 tile for given bpp and format."""
        if format:
            fmt = format.lower().replace("-", "_")
            if fmt in ("md", "genesis", "megadrive", "gba", "nds", "snes4", "snes_4bpp", "snes"):
                return 32
            if fmt in ("gb", "nes", "gameboy"):
                return 16
            if fmt in ("snes8", "snes_8bpp", "mode7"):
                return 64

        sizes = {1: 8, 2: 16, 4: 32, 8: 64}
        return sizes.get(bpp, 8)

    @classmethod
    def inject_glyph(
        cls,
        buffer: Union[bytearray, bytes],
        tile_index_or_offset: int,
        char_or_tile: Union[str, Tile],
        bpp: int = 1,
        format: Optional[str] = None,
        fg_color: int = 1,
        bg_color: int = 0,
        is_offset: bool = False,
    ) -> bytearray:
        """
        Injects an encoded 8x8 character tile into a ROM or VRAM buffer.
        If is_offset is False, tile_index_or_offset is treated as a 0-based tile index.
        """
        out = buffer if isinstance(buffer, bytearray) else bytearray(buffer)
        tile_size = cls.get_tile_byte_size(bpp=bpp, format=format)
        target_offset = tile_index_or_offset if is_offset else (tile_index_or_offset * tile_size)

        encoded_tile = cls.encode_glyph_tile(
            char_or_tile, bpp=bpp, format=format, fg_color=fg_color, bg_color=bg_color
        )

        if target_offset + len(encoded_tile) > len(out):
            # Extend buffer if needed
            out.extend(b"\x00" * (target_offset + len(encoded_tile) - len(out)))

        out[target_offset : target_offset + len(encoded_tile)] = encoded_tile
        return out

    @classmethod
    def inject_charset(
        cls,
        buffer: Union[bytearray, bytes],
        start_tile_index: int,
        chars: str,
        bpp: int = 1,
        format: Optional[str] = None,
        fg_color: int = 1,
        bg_color: int = 0,
    ) -> Tuple[bytearray, Dict[str, int]]:
        """
        Batch-injects a string of characters into consecutive tile slots in a tileset buffer.
        Returns the modified buffer and a dictionary mapping each character to its tile index.
        """
        out = bytearray(buffer)
        mapping: Dict[str, int] = {}

        curr_tile = start_tile_index
        for ch in chars:
            out = cls.inject_glyph(
                out,
                tile_index_or_offset=curr_tile,
                char_or_tile=ch,
                bpp=bpp,
                format=format,
                fg_color=fg_color,
                bg_color=bg_color,
                is_offset=False,
            )
            mapping[ch] = curr_tile
            curr_tile += 1

        return out, mapping

    @classmethod
    def extract_glyph(
        cls,
        buffer: bytes,
        tile_index_or_offset: int,
        bpp: int = 1,
        format: Optional[str] = None,
        is_offset: bool = False,
        char: str = "?",
    ) -> Glyph:
        """Extracts and decodes a tile from a binary buffer into a high-level Glyph object."""
        from miorom.text.font_builder import Glyph

        tile_size = cls.get_tile_byte_size(bpp=bpp, format=format)
        offset = tile_index_or_offset if is_offset else (tile_index_or_offset * tile_size)

        if offset + tile_size > len(buffer):
            raise ParseError(f"Tile at offset {offset} exceeds buffer size {len(buffer)}.")

        chunk = buffer[offset : offset + tile_size]
        tile = decode_tile(chunk, bpp=bpp, format=format)
        width = cls.calculate_glyph_width(tile, padding=1)
        bitmap = [255 if p != 0 else 0 for p in tile.pixels]

        return Glyph(char=char, width=8, height=8, advance=width + 1, bitmap=bitmap)

    @classmethod
    def generate_vwf_table(
        cls,
        chars: str,
        space_width: int = 3,
        padding: int = 1,
        min_width: int = 1,
        max_width: int = 8,
    ) -> bytes:
        """
        Generates a binary proportional Variable-Width Font (VWF) width table.
        Emits 1 byte per character representing exact pixel width.
        """
        out = bytearray()
        for ch in chars:
            w = cls.calculate_glyph_width(
                ch,
                padding=padding,
                space_width=space_width,
                min_width=min_width,
                max_width=max_width,
            )
            out.append(w)
        return bytes(out)

    @classmethod
    def generate_tbl_mapping(cls, chars: str, start_code: int = 0x80) -> str:
        """
        Generates a standard .tbl character mapping text file matching injected glyph slots.
        """
        lines: List[str] = []
        code = start_code
        for ch in chars:
            lines.append(f"{code:02X}={ch}")
            code += 1
        return "\n".join(lines) + "\n"
